		<h2>KSU Team Members Find Success at CHAMP</h2>
		<p>
			This weekend, our team member David Dreyer & alumni Brendan Steele attended Akron Makerspace's CHAMP combat event. This event hosted a number of 1 lb & 3 lb bots across the local area. Out of all the teams there, our members walked away with 1st place in both weight classes.
		</p>

		<h2>Baby Cosmo</h2>
		<img src="/blog/img/babycosmo.jpg" alt="Baby Cosmo" class="article-img" />
		<p>
			Baby Cosmo is Brendan's 1 lb vertical spinner bot, very much inspired by Endgame in the Battlebots show. Its initial version was debuted during our team's 1.5 lb plastic event last Fall. Brendan has worked since to make it competitive at the 1 lb full combat level.
		</p>

		<h2>Katana</h2>
		<img src="/blog/img/Katana.jpg" alt="Katana" class="article-img" />
		<p>
			Katana is David's 3 lb vertical spinner bot, based on Witch Doctor and Hypershock from Battlebots. Similar to Brendan's, it first began as a 1.5 lb bot for our in-house mini-event. Following the event, David redesigned it for the 3 lb weight class, and has taken it to several NHRL events across the last 6 months.
		</p>

